import { chromium } from '@playwright/test';
const [,, out, w, h, players] = process.argv;
const b = await chromium.launch({ channel: 'chrome', args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist'] });
const p = await b.newPage({ viewport: { width: +w, height: +h } });
await p.goto('http://localhost:5173/?speed=4');
await p.click(`.count:text-is("${players}")`);
await p.click('.lobby .primary.big');
await p.waitForSelector('.act.attack', { timeout: 60000 });
await p.waitForTimeout(800);
await p.screenshot({ path: out });
await b.close();
